export function normalizeMenuText(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[!?.:;,]+$/g, '')
    .trim();
}

const INDEX = new Map<string, { en: string; es: string }>();
for (const [pt, en, es] of ENTRIES) INDEX.set(normalizeMenuText(pt), { en, es });

// null = termo desconhecido (quem chama decide o fallback).
export function translateFromGlossary(text: string, language: GlossaryLanguage): string | null {
  if (!text) return null;
  return INDEX.get(normalizeMenuText(text))?.[language] ?? null;
}

export const GLOSSARY_SIZE = INDEX.size;
